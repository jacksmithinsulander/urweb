fn main() {
    let args: Vec<String> = std::env::args().collect();
    let code = dispatch(&args[1..]);
    process::exit(code);
}

fn dispatch(args: &[String]) -> i32 {
    match args.first().map(|s| s.as_str()) {
        None => {
            eprintln!("usage: urweb <command> [args...]");
            eprintln!("Run 'urweb -help' for more information.");
            1
        }
        Some("new") => {
            // urweb new [--lib] <name>
            let rest = &args[1..];
            if rest.first().map_or(false, |s| s == "--lib" || s == "-lib") {
                let name = rest.get(1).map(|s| s.as_str()).unwrap_or("");
                if name.is_empty() {
                    eprintln!("usage: urweb new --lib <name>");
                    return 1;
                }
                new_project(ProjectKind::Library, name)
            } else {
                let name = rest.first().map(|s| s.as_str()).unwrap_or("");
                if name.is_empty() {
                    eprintln!("usage: urweb new <name>");
                    return 1;
                }
                new_project(ProjectKind::App, name)
            }
        }
        Some("build") => build_project(),
        Some("install") => {
            let spec = args.get(1).map(|s| s.as_str()).unwrap_or("");
            if spec.is_empty() {
                eprintln!("usage: urweb install <author/repo>");
                1
            } else {
                install_package(spec)
            }
        }
        Some("fmt") => fmt_command(&args[1..]),
        Some("daemon") => daemon_command(&args[1..]),
        Some(_) => run_compiler_args(args),
    }
}

