#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ProjectKind {
    App,
    Library,
}

fn validate_project_name(name: &str) -> Result<(), String> {
    if name.is_empty() {
        return Err("project name cannot be empty".into());
    }
    if !name.chars().next().map_or(false, |c| c.is_alphabetic()) {
        return Err(format!("project name must start with a letter: '{}'", name));
    }
    if !name.chars().all(|c| c.is_alphanumeric() || c == '_') {
        return Err(format!(
            "project name must contain only letters, digits, or underscores: '{}'",
            name
        ));
    }
    Ok(())
}

fn capitalize(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
    }
}

/// Returns the kind-specific created file paths for display (e.g. .urs for lib, style/ for app).
fn kind_specific_created_files(kind: ProjectKind, name: &str) -> Vec<String> {
    let mut out = vec![];
    if kind == ProjectKind::Library {
        out.push(format!("{name}/{name}.urs"));
    }
    if kind == ProjectKind::App {
        out.push(format!("{name}/style/scss/main.scss"));
        out.push(format!("{name}/style/css/main.css"));
    }
    out
}

fn write_file(path: &str, content: &str) -> std::io::Result<()> {
    std::fs::write(path, content)
}

