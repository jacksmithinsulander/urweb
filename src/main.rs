fn fmt_command(args: &[String]) -> i32 {
    let mut check_mode = false;
    let mut _width: u32 = 80;
    let mut files: Vec<String> = vec![];
    let mut args_iter = args.iter();
    while let Some(arg) = args_iter.next() {
        let (flag, opt_val) = if let Some(eq) = arg.find('=') {
            let (f, v) = arg.split_at(eq);
            (f, Some(v[1..].to_string()))
        } else {
            (arg.as_str(), None)
        };
        match flag {
            "-help" | "--help" | "-h" => {
                println!("urweb fmt [options] [files...]");
                println!("  If no files: format all .ur/.urs in project (from urweb.toml)");
                println!("  Otherwise: format the given files.");
                println!("  -check, --check: check only; exit 1 if would reformat (CI mode)");
                println!("  -w N, --width N, --width=N: line width (default 80)");
                return 0;
            }
            "-check" | "--check" => {
                check_mode = true;
            }
            "-w" | "--width" => {
                if let Some(n) = opt_val
                    .or_else(|| args_iter.next().cloned())
                    .and_then(|s| s.parse::<u32>().ok())
                {
                    _width = n;
                }
            }
            f if is_file_arg(f) => {
                files.push(f.to_string());
            }
            other => {
                eprintln!("warning: unknown fmt flag: {}", other);
            }
        }
    }

    if files.is_empty() {
        // Project mode
        if !file_exists("urweb.toml") {
            eprintln!("error: urweb.toml not found; run from project directory or specify files");
            return 1;
        }
        let toml_content = match std::fs::read_to_string("urweb.toml") {
            Ok(s) => s,
            Err(e) => {
                eprintln!("error: {}", e);
                return 1;
            }
        };
        let entries = parse_toml(&toml_content);
        let entry = toml_get(&entries, "build.entry").unwrap_or("");
        if entry.is_empty() {
            eprintln!("error: urweb.toml: [build] entry is required");
            return 1;
        }
        // Discover .ur/.urs files from the .urp
        let urp_path = format!("{}.urp", entry);
        if !file_exists(&urp_path) {
            eprintln!("error: project .urp not found: {}", urp_path);
            return 1;
        }
        // Read source list from .urp (simple: lines that don't start with a directive keyword)
        if let Ok(content) = std::fs::read_to_string(&urp_path) {
            for line in content.lines() {
                let line = line.trim();
                if should_skip_urp_line(line) {
                    continue;
                }
                // Skip directive lines
                let directive_keywords = [
                    "database",
                    "sql",
                    "prefix",
                    "rewrite",
                    "file",
                    "library",
                    "link",
                    "ffi",
                    "effectful",
                    "benignEffectful",
                    "clientOnly",
                    "serverOnly",
                    "jsFunc",
                    "timeout",
                    "sigfile",
                    "debug",
                ];
                if directive_keywords.iter().any(|kw| line.starts_with(kw)) {
                    continue;
                }
                // Assume it's a module name
                let ur = format!("{}.ur", line);
                let urs = format!("{}.urs", line);
                if std::path::Path::new(&ur).exists() {
                    files.push(ur);
                }
                if std::path::Path::new(&urs).exists() {
                    files.push(urs);
                }
            }
        }
        if files.is_empty() {
            println!("no .ur or .urs files found");
            return 0;
        }
    }

    let mut all_ok = true;
    for f in &files {
        if !f.ends_with(".ur") && !f.ends_with(".urs") {
            eprintln!("error: {} is not a .ur or .urs file", f);
            all_ok = false;
            continue;
        }
        if !file_exists(f) {
            eprintln!("error: {} not found", f);
            all_ok = false;
            continue;
        }
        // Placeholder: formatter not yet implemented
        if check_mode {
            // In check mode, succeed silently (formatter not implemented)
            eprintln!("note: formatter not yet implemented; {} skipped", f);
        } else {
            eprintln!("note: formatter not yet implemented; {} skipped", f);
        }
    }
    if all_ok {
        0
    } else {
        1
    }
}

