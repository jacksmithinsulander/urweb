/// Simple TOML reader: returns `(key, value)` pairs.
fn parse_toml(content: &str) -> Vec<(String, String)> {
    let mut section = String::new();
    let mut entries = vec![];
    for line in content.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if line.starts_with('[') && line.ends_with(']') {
            section = line[1..line.len() - 1].trim().to_string();
            continue;
        }
        if let Some(eq) = line.find('=') {
            let key = line[..eq].trim();
            let raw_val = line[eq + 1..].trim();
            let val = if raw_val.starts_with('"') && raw_val.ends_with('"') && raw_val.len() >= 2 {
                raw_val[1..raw_val.len() - 1].to_string()
            } else {
                raw_val.to_string()
            };
            let full_key = if section.is_empty() {
                key.to_string()
            } else {
                format!("{}.{}", section, key)
            };
            entries.push((full_key, val));
        }
    }
    entries
}

fn toml_get<'a>(entries: &'a [(String, String)], key: &str) -> Option<&'a str> {
    entries
        .iter()
        .find(|(k, _)| k == key)
        .map(|(_, v)| v.as_str())
}

fn is_lib_project(kind: &str) -> bool {
    kind == "lib"
}

fn parse_boot(value: &str) -> bool {
    value == "true"
}

fn sass_tool_available(has_sass: bool, has_sassc: bool) -> bool {
    has_sass || has_sassc
}

fn has_sass_or_sassc() -> bool {
    let has_sass = std::process::Command::new("which")
        .arg("sass")
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .map_or(false, |s| s.success());
    let has_sassc = std::process::Command::new("which")
        .arg("sassc")
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .map_or(false, |s| s.success());
    sass_tool_available(has_sass, has_sassc)
}

fn should_add_ccompiler(cc: &str) -> bool {
    !cc.is_empty()
}

fn command_succeeded(status: &std::io::Result<std::process::ExitStatus>) -> bool {
    status.as_ref().map_or(false, |s| s.success())
}

fn is_file_arg(arg: &str) -> bool {
    !arg.starts_with('-')
}

fn should_skip_urp_line(line: &str) -> bool {
    line.is_empty() || line.starts_with('#')
}

fn file_exists(path: &str) -> bool {
    std::path::Path::new(path).exists()
}

fn is_unknown_compiler_flag(flag: &str, arg: &str) -> bool {
    flag.is_empty() || arg.starts_with('-')
}

fn is_valid_limit(n: i32) -> bool {
    n >= 0
}

fn build_project() -> i32 {
    let toml_path = "urweb.toml";
    if !file_exists(toml_path) {
        eprintln!(
            "error: urweb.toml not found in current directory\n\
Run 'urweb new <name>' to create a project, then 'cd <name> && urweb build'"
        );
        return 1;
    }

    let toml_content = match std::fs::read_to_string(toml_path) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("error reading urweb.toml: {}", e);
            return 1;
        }
    };
    let entries = parse_toml(&toml_content);

    let kind = toml_get(&entries, "package.kind").unwrap_or("app");
    let entry = toml_get(&entries, "build.entry").unwrap_or("");
    let db = toml_get(&entries, "build.db").unwrap_or("sqlite");
    let cc = toml_get(&entries, "build.ccompiler").unwrap_or("");
    let is_lib = is_lib_project(kind);
    let boot = parse_boot(toml_get(&entries, "build.boot").unwrap_or("false"));
    let scss = toml_get(&entries, "style.scss");
    let css = toml_get(&entries, "style.css");

    if entry.is_empty() {
        eprintln!("error: urweb.toml: [build] entry is required");
        return 1;
    }

    // Compile SCSS → CSS if configured
    if let (Some(scss_path), Some(css_path)) = (scss, css) {
        if has_sass_or_sassc() {
            let has_sass = std::process::Command::new("which")
                .arg("sass")
                .stdout(std::process::Stdio::null())
                .stderr(std::process::Stdio::null())
                .status()
                .map_or(false, |s| s.success());
            println!("  Compiling SCSS...");
            let sass_arg = format!("{}:{}", scss_path, css_path);
            let status = if has_sass {
                std::process::Command::new("sass")
                    .args([sass_arg.as_str(), "--no-source-map", "--style=expanded"])
                    .status()
            } else {
                std::process::Command::new("sassc")
                    .args([scss_path, css_path])
                    .status()
            };
            if !command_succeeded(&status) {
                eprintln!("error: SCSS compilation failed");
                return 1;
            }
        }
    }

    println!(
        "  {} {}...",
        if is_lib { "Type-checking" } else { "Building" },
        entry
    );

    // Build the argument list to pass to the compiler
    let mut args: Vec<String> = vec![];
    if should_add_ccompiler(cc) {
        args.extend(["-ccompiler".to_string(), cc.to_string()]);
    }
    if boot {
        args.push("-boot".to_string());
    }
    if is_lib {
        args.extend(["-tc".to_string(), entry.to_string()]);
    } else {
        args.extend([
            "-dbms".to_string(),
            db.to_string(),
            "-db".to_string(),
            format!("{}.db", entry),
            "-sql".to_string(),
            format!("{}.sql", entry),
            entry.to_string(),
        ]);
    }

    // Call the compiler pipeline (currently all stubs)
    run_compiler_args(&args)
}

